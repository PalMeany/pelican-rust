#!/usr/bin/env python3
"""Generate crates/pelican-db/src/column_order.rs: physical column order per
backend. Laravel's `SELECT *` + `toArray()` emits attributes in this order, so
some API payloads depend on it (application-api.md, models-services.md)."""
import pathlib, re, sys
schema = pathlib.Path(sys.argv[1]); out = pathlib.Path(sys.argv[2])

def cols_mysql(f):
    t = {}; cur = None
    for l in open(f):
        m = re.match(r'CREATE TABLE `(\w+)`', l)
        if m: cur = m.group(1); t[cur] = []; continue
        m = re.match(r'\s+`(\w+)` ', l)
        if cur and m: t[cur].append(m.group(1))
        if l.startswith(')'): cur = None
    return t
def cols_pg(f):
    t = {}; cur = None
    for l in open(f):
        m = re.match(r'CREATE TABLE (\w+) \(', l)
        if m: cur = m.group(1); t[cur] = []; continue
        m = re.match(r'\s+"?(\w+)"? ', l)
        if cur and m: t[cur].append(m.group(1))
        if l.startswith(');'): cur = None
    return t
def cols_sqlite(f):
    t = {}
    for l in open(f):
        m = re.match(r'CREATE TABLE "?(\w+)"? \((.*)\)', l)
        if m: t[m.group(1)] = re.findall(r'(?:^|, )"(\w+)" ', m.group(2))
    return t

S = {'Mysql': cols_mysql(schema/'mysql.sql'), 'Mariadb': cols_mysql(schema/'mariadb.sql'),
     'Pgsql': cols_pg(schema/'pgsql.sql'), 'Sqlite': cols_sqlite(schema/'sqlite.sql')}
lines = ["//! Generated by scripts/schema/column_order.py — do not edit.",
         "//! Physical column order per backend (order of `SELECT *` / Eloquent `toArray()`).", "",
         "use crate::connect::Driver;", "",
         "pub fn columns(driver: Driver, table: &str) -> Option<&'static [&'static str]> {",
         "    match driver {"]
for drv, tables in S.items():
    lines.append(f"        Driver::{drv} => match table {{")
    for t in sorted(tables):
        cs = ", ".join(f'"{c}"' for c in tables[t])
        lines.append(f'            "{t}" => Some(&[{cs}]),')
    lines.append("            _ => None,")
    lines.append("        },")
lines += ["    }", "}", ""]
out.write_text("\n".join(lines))
same = all(S['Sqlite'].get(t) == S['Pgsql'].get(t) for t in S['Pgsql'])
print("sqlite==pgsql order:", same, "| mysql==mariadb order:", all(S['Mysql'].get(t)==S['Mariadb'].get(t) for t in S['Mysql']))
