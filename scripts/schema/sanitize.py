#!/usr/bin/env python3
"""Turn raw schema dumps taken from the ORIGINAL panel into clean, ordered
statement files used by `pelican db:install` (fresh installs).

usage: sanitize.py <raw-dir> <out-dir>
  raw-dir: mariadb.schema.sql mysql.schema.sql pgsql.schema.sql sqlite.schema.sql migrations.txt
"""
import pathlib, re, sys

raw, out = map(pathlib.Path, sys.argv[1:3])
out.mkdir(parents=True, exist_ok=True)

def split_statements(text):
    stmts, cur, quote = [], [], None
    for ch in text:
        cur.append(ch)
        if quote:
            if ch == quote:
                quote = None
        elif ch in "'\"`":
            quote = ch
        elif ch == ';':
            s = ''.join(cur).strip()
            cur = []
            if s and s != ';':
                stmts.append(s)
    tail = ''.join(cur).strip()
    if tail:
        stmts.append(tail)
    return stmts

def write(name, stmts):
    body = "\n\n".join(s if s.endswith(';') else s + ';' for s in stmts)
    (out / name).write_text("-- Generated by scripts/schema/refresh.sh from the original panel. Do not edit.\n\n" + body + "\n")

# MySQL / MariaDB
for src, dst in (("mariadb.schema.sql", "mariadb.sql"), ("mysql.schema.sql", "mysql.sql")):
    lines = [l for l in (raw / src).read_text().splitlines()
             if not l.startswith(("/*!", "/*M!", "--")) and l.strip()]
    stmts = [s for s in split_statements("\n".join(lines)) if s.startswith("CREATE")]
    write(dst, stmts)

# PostgreSQL
lines = []
for l in (raw / "pgsql.schema.sql").read_text().splitlines():
    if l.startswith(("\\", "--", "SET ", "SELECT pg_catalog.set_config")) or not l.strip():
        continue
    lines.append(l)
text = "\n".join(lines)
text = re.sub(r"\bpublic\.", "", text)
stmts = [s for s in split_statements(text)
         if not s.startswith(("COMMENT ON", "ALTER TABLE ONLY") ) or s.startswith("ALTER TABLE ONLY")]
write("pgsql.sql", stmts)

# SQLite
stmts = [s for s in split_statements((raw / "sqlite.schema.sql").read_text())
         if "sqlite_sequence" not in s]
write("sqlite.sql", stmts)

# Migrations applied by the original (inserted with batch = 1 on fresh install)
names = [l.strip() for l in (raw / "migrations.txt").read_text().splitlines() if l.strip()]
(out / "migrations.txt").write_text("\n".join(names) + "\n")
print(f"ok: {len(names)} migrations")
